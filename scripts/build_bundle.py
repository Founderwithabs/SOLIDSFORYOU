#!/usr/bin/env python3
"""Build single-file workflow prompts that work in any Claude chat.

A workflow prompt (such as the Master Skill) names the tools it uses in a
registry table that follows a "<!-- REGISTRY" marker. This script appends the
full prompt of every tool in that table, so one file carries the whole
workflow. Run it after changing the workflow or any tool it uses.

  python3 scripts/build_bundle.py          rebuild everything
  python3 scripts/build_bundle.py --check  exit 1 if a bundle is out of date
"""

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent

# workflow prompt -> (bundled output, files placed right after the prompt)
BUNDLES = {
    "plugins/master/skills/master/master.md": (
        "dist/master-full.md",
        ["plugins/master/skills/master/toolbox.md"],
    ),
}


def registry_paths(text):
    """Prompt paths from the table that follows the REGISTRY marker."""
    lines = text[text.index("<!-- REGISTRY"):].splitlines()[1:]
    paths = []
    for line in lines:
        if not line.startswith("|"):
            if paths:
                break
            continue
        for p in re.findall(r"`(plugins/[^`]+\.md)`", line):
            if p not in paths:
                paths.append(p)
    return paths


def strip_frontmatter(text):
    if text.startswith("---\n"):
        end = text.find("\n---\n", 4)
        if end != -1:
            return text[end + 5:].lstrip()
    return text


def build(src, extras):
    text = (ROOT / src).read_text(encoding="utf-8")
    parts = [
        f"<!-- Generated by scripts/build_bundle.py from {src}. "
        "Do not edit by hand: edit the source files and rebuild. -->",
        "",
        "Required Notice: Copyright Solids for You Private Limited "
        "(https://github.com/Founderwithabs/SOLIDSFORYOU). Licensed under the "
        "PolyForm Noncommercial License 1.0.0 "
        "(https://polyformproject.org/licenses/noncommercial/1.0.0). "
        "For a commercial license, email shashwat@solidsforyou.com.",
        "",
        text.rstrip(),
    ]
    for p in extras:
        parts += ["", "---", "", (ROOT / p).read_text(encoding="utf-8").rstrip()]
    parts += [
        "",
        "---",
        "",
        "# Appendix: the skills this workflow uses",
        "",
        "Below is the full text of each skill in the registry. Where the "
        "workflow says to use a skill that is not installed, follow its "
        "section here.",
    ]
    for p in registry_paths(text):
        body = strip_frontmatter((ROOT / p).read_text(encoding="utf-8")).rstrip()
        parts += ["", "---", "", f"## Skill: `{p}`", "", body]
    return "\n".join(parts) + "\n"


def main():
    check = "--check" in sys.argv
    stale = []
    for src, (out, extras) in BUNDLES.items():
        content = build(src, extras)
        path = ROOT / out
        if path.exists() and path.read_text(encoding="utf-8") == content:
            print(f"Up to date: {out}")
        elif check:
            stale.append(out)
        else:
            path.parent.mkdir(exist_ok=True)
            path.write_text(content, encoding="utf-8")
            print(f"Wrote {out} ({len(content.splitlines())} lines)")
    if stale:
        sys.exit("Out of date (run python3 scripts/build_bundle.py): " + ", ".join(stale))


if __name__ == "__main__":
    main()
